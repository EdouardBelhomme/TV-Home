"""Writes app/installed.js: the apps the TV shows in its own app list (vd_applist over sdb).

The Tizen API lists ~230 entries, most of them system services; vd_applist is the list Smart Hub
uses. Re-run after installing or removing an app (needs the TV's Host PC IP set to this computer).

  sync_installed.py TV_IP
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.expanduser("~/tvctl-lib"))
from adb_shell.adb_device import AdbDeviceTcp  # noqa: E402

SKIP = {"TVHomeEdou.Accueil"}
RENAME = {"TizenBrewNextGeneration": "TizenBrew", "Gallery (Galerie)": "Galerie", "Découvrez l'Assistant Google": "Assistant Google"}
OUT = os.path.join(os.path.dirname(__file__), "..", "app", "installed.js")


def field(record, key):
    m = re.search(re.escape(key) + r"\s*=([^\n]*?)-------------", record)
    return m.group(1).strip() if m else ""


def short_name(title):
    title = RENAME.get(title, title)
    # Store titles often carry a tagline: "TF1+ : Streaming, TV en Direct", "Spotify - Musique et podcasts".
    return re.split(r"\s+[:\-–]\s+", title)[0]


def main():
    dev = AdbDeviceTcp(sys.argv[1], 26101, default_transport_timeout_s=30)
    dev.connect(auth_timeout_s=5)
    raw = dev.shell("0 vd_applist", timeout_s=60)
    dev.close()
    apps = []
    for record in raw.split("app_id                                =")[1:]:
        samsung_id = record.split("-")[0].strip()
        tizen_id = field(record, "app_tizen_id")
        if not tizen_id or tizen_id in SKIP or field(record, "is_hidden") == "1":
            continue
        apps.append({"name": short_name(field(record, "app_title")), "id": tizen_id, "samsungId": samsung_id,
                     "index": int(field(record, "app_index") or 999)})
    apps.sort(key=lambda a: a["index"])
    for a in apps:
        del a["index"]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/sync_installed.py from the TV's own app list. Do not edit by hand.\n")
        f.write("window.TV_INSTALLED_APPS = %s;\n" % json.dumps(apps, ensure_ascii=False, indent=2))
    print("%d applis ecrites dans app/installed.js" % len(apps))


if __name__ == "__main__":
    main()
